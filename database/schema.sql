CREATE OR REPLACE PROCEDURE AIRLINE_BOOK_FLIGHT_SEAT_USP (
    P_PASSENGER_ID      IN NUMBER,
    P_DYNAMIC_PRICE_ID  IN NUMBER,
    P_SEAT_NO           IN VARCHAR2,
    P_PNR_NO            OUT VARCHAR2,
    P_BOOKING_ID        OUT NUMBER,
    P_DATA              OUT VARCHAR2
)
IS
    V_AVAIL_COUNT NUMBER;
    V_SEAT_STATUS VARCHAR2(20);
    V_BASE_PRICE NUMBER(10,2);
    V_SURCHARGE NUMBER(10,2) := 0.00;
    V_TOTAL_PRICE NUMBER(10,2);
    V_FLIGHT_ID NUMBER;
    V_PNR VARCHAR2(20);
    V_NEW_BOOKING_ID NUMBER;
BEGIN
    -- Check dynamic price record and available seats count
    SELECT AVAILABLE_SEATS, CURRENT_PRICE, FLIGHT_ID
    INTO V_AVAIL_COUNT, V_BASE_PRICE, V_FLIGHT_ID
    FROM AIRLINE_FLIGHT_DYNAMIC_PRICE_MSTR_TBL
    WHERE DYNAMIC_PRICE_ID = P_DYNAMIC_PRICE_ID
      AND IS_ACTIVE = 'Y';

    IF V_AVAIL_COUNT <= 0 THEN
        P_DATA := 'No available seats remaining on this flight.';
        RETURN;
    END IF;

    -- Check seat status in booking table if exists
    BEGIN
        SELECT STATUS INTO V_SEAT_STATUS
        FROM AIRLINE_FLIGHT_SEAT_BOOKING_TBL
        WHERE DYNAMIC_PRICE_ID = P_DYNAMIC_PRICE_ID
          AND UPPER(SEAT_NO) = UPPER(P_SEAT_NO);

        IF V_SEAT_STATUS = 'BOOKED' THEN
            P_DATA := 'Seat ' || P_SEAT_NO || ' is already booked!';
            RETURN;
        END IF;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            NULL; -- Will be created during booking
    END;

    -- Calculate price surcharge if seat master exists
    BEGIN
        SELECT PRICE_SURCHARGE INTO V_SURCHARGE
        FROM AIRLINE_FLIGHT_SEAT_MSTR_TBL
        WHERE FLIGHT_ID = V_FLIGHT_ID
          AND UPPER(SEAT_NO) = UPPER(P_SEAT_NO);
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            V_SURCHARGE := 0.00;
    END;

    V_TOTAL_PRICE := V_BASE_PRICE + V_SURCHARGE;
    V_NEW_BOOKING_ID := AIRLINE_TICKET_BOOKING_TRANSACTION_SEQ.NEXTVAL;

    -- Generate random 6-character PNR code
    V_PNR := 'PNR' || DBMS_RANDOM.STRING('U', 5);
    P_PNR_NO := V_PNR;
    P_BOOKING_ID := V_NEW_BOOKING_ID;

    -- 1. Insert transaction record
    INSERT INTO AIRLINE_TICKET_BOOKING_TRANSACTION_TBL (
        BOOKING_ID, PASSENGER_ID, DYNAMIC_PRICE_ID, PNR_NO, SEAT_NO, BOOKING_STATUS, PAYMENT_STATUS, BOOKING_AMOUNT, CREATED_BY
    ) VALUES (
        V_NEW_BOOKING_ID, P_PASSENGER_ID, P_DYNAMIC_PRICE_ID, V_PNR, UPPER(P_SEAT_NO), 'CONFIRMED', 'PAID', V_TOTAL_PRICE, 'SYSTEM'
    );

    -- 2. Update/Insert seat status entry
    MERGE INTO AIRLINE_FLIGHT_SEAT_BOOKING_TBL SB
    USING DUAL ON (SB.DYNAMIC_PRICE_ID = P_DYNAMIC_PRICE_ID AND UPPER(SB.SEAT_NO) = UPPER(P_SEAT_NO))
    WHEN MATCHED THEN
        UPDATE SET STATUS = 'BOOKED', BOOKING_ID = V_NEW_BOOKING_ID, BOOKED_BY_PASSENGER_ID = P_PASSENGER_ID, FINAL_SEAT_PRICE = V_TOTAL_PRICE, UPDATED_TIME = SYSTIMESTAMP
    WHEN NOT MATCHED THEN
        INSERT (SEAT_BOOKING_ID, DYNAMIC_PRICE_ID, SEAT_NO, STATUS, BOOKING_ID, BOOKED_BY_PASSENGER_ID, FINAL_SEAT_PRICE)
        VALUES (AIRLINE_FLIGHT_SEAT_BOOKING_SEQ.NEXTVAL, P_DYNAMIC_PRICE_ID, UPPER(P_SEAT_NO), 'BOOKED', V_NEW_BOOKING_ID, P_PASSENGER_ID, V_TOTAL_PRICE);

    -- 3. Deduct available seats count from AIRLINE_FLIGHT_DYNAMIC_PRICE_MSTR_TBL
    UPDATE AIRLINE_FLIGHT_DYNAMIC_PRICE_MSTR_TBL
    SET AVAILABLE_SEATS = AVAILABLE_SEATS - 1,
        UPDATED_TIME = SYSTIMESTAMP
    WHERE DYNAMIC_PRICE_ID = P_DYNAMIC_PRICE_ID;

    COMMIT;
    P_DATA := 'Ticket booked successfully!';

CREATE OR REPLACE PROCEDURE AIRLINE_GET_FLIGHT_SEAT_MAP_USP (
    P_DYNAMIC_PRICE_ID  IN NUMBER,
    P_FLIGHT_CURSOR     OUT SYS_REFCURSOR,
    P_SEAT_CURSOR       OUT SYS_REFCURSOR,
    P_PASSENGER_CURSOR  OUT SYS_REFCURSOR,
    P_DATA              OUT VARCHAR2
)
IS
    V_FLIGHT_ID NUMBER;
    V_BASE_PRICE NUMBER(10,2);
    V_SEAT_MSTR_CNT NUMBER;
    V_SB_CNT NUMBER;
BEGIN
    -- 1. Open flight schedule details cursor
    OPEN P_FLIGHT_CURSOR FOR
        SELECT 
            DP.DYNAMIC_PRICE_ID,
            DP.FLIGHT_ID,
            F.FLIGHT_NO,
            F.FLIGHT_NAME,
            C.COMPANY_NAME,
            SA.AIRPORT_CODE AS SOURCE_CODE,
            SC.CITY_NAME    AS SOURCE_CITY,
            DA.AIRPORT_CODE AS DEST_CODE,
            DC.CITY_NAME    AS DEST_CITY,
            TO_CHAR(DP.FLIGHT_DATE, 'YYYY-MM-DD') AS FLIGHT_DATE,
            TO_CHAR(DP.DEPARTURE_TIME, 'HH24:MI') AS DEP_TIME,
            TO_CHAR(DP.ARRIVAL_TIME, 'HH24:MI')   AS ARR_TIME,
            NVL(DP.TOTAL_SEATS, 180)     AS TOTAL_SEATS,
            NVL(DP.AVAILABLE_SEATS, 180) AS AVAIL_SEATS,
            NVL(DP.CURRENT_PRICE, 0)     AS CURRENT_PRICE
        FROM AIRLINE_FLIGHT_DYNAMIC_PRICE_MSTR_TBL DP
        LEFT JOIN AIRLINE_FLIGHT_MSTR_TBL F ON DP.FLIGHT_ID = F.FLIGHT_ID
        LEFT JOIN AIRLINE_FLIGHT_COMPANY_MSTR_TBL C ON F.COMPANY_ID = C.COMPANY_ID
        LEFT JOIN AIRLINE_AIRPORT_MSTR_TBL SA ON DP.SOURCE_AIRPORT_ID = SA.AIRPORT_ID
        LEFT JOIN AIRLINE_CITY_MSTR_TBL SC ON SA.CITY_ID = SC.CITY_ID
        LEFT JOIN AIRLINE_AIRPORT_MSTR_TBL DA ON DP.DEST_AIRPORT_ID = DA.AIRPORT_ID
        LEFT JOIN AIRLINE_CITY_MSTR_TBL DC ON DA.CITY_ID = DC.CITY_ID
        WHERE DP.DYNAMIC_PRICE_ID = P_DYNAMIC_PRICE_ID;

    -- Fetch flight id and current base price
    BEGIN
        SELECT FLIGHT_ID, CURRENT_PRICE INTO V_FLIGHT_ID, V_BASE_PRICE
        FROM AIRLINE_FLIGHT_DYNAMIC_PRICE_MSTR_TBL
        WHERE DYNAMIC_PRICE_ID = P_DYNAMIC_PRICE_ID;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            P_DATA := 'Flight schedule not found';
            RETURN;
    END;

    -- Ensure seat master entries exist for flight
    SELECT COUNT(*) INTO V_SEAT_MSTR_CNT FROM AIRLINE_FLIGHT_SEAT_MSTR_TBL WHERE FLIGHT_ID = V_FLIGHT_ID;
    IF V_SEAT_MSTR_CNT = 0 THEN
        FOR r IN 1..30 LOOP
            FOR col_idx IN 1..6 LOOP
                DECLARE
                    v_col_char CHAR(1) := SUBSTR('ABCDEF', col_idx, 1);
                    v_seat_no VARCHAR2(10) := r || v_col_char;
                    v_class VARCHAR2(20) := CASE WHEN r <= 3 THEN 'BUSINESS' WHEN r <= 6 THEN 'PREMIUM' ELSE 'ECONOMY' END;
                    v_surch NUMBER(10,2) := CASE WHEN r <= 3 THEN 1500.00 WHEN r <= 6 THEN 500.00 WHEN r IN (10,11) THEN 300.00 ELSE 0.00 END;
                    v_type VARCHAR2(20) := CASE WHEN v_col_char IN ('A','F') THEN 'WINDOW' WHEN v_col_char IN ('C','D') THEN 'AISLE' ELSE 'MIDDLE' END;
                BEGIN
                    IF v_class = 'ECONOMY' AND r NOT IN (10,11) THEN
                        IF v_type = 'WINDOW' THEN v_surch := 150.00;
                        ELSIF v_type = 'AISLE' THEN v_surch := 100.00;
                        END IF;
                    END IF;

                    INSERT INTO AIRLINE_FLIGHT_SEAT_MSTR_TBL (
                        SEAT_ID, FLIGHT_ID, SEAT_NO, SEAT_ROW, SEAT_COL, SEAT_CLASS, SEAT_TYPE, PRICE_SURCHARGE, CREATED_BY
                    ) VALUES (
                        AIRLINE_FLIGHT_SEAT_MSTR_SEQ.NEXTVAL, V_FLIGHT_ID, v_seat_no, r, v_col_char, v_class, v_type, v_surch, 'SYSTEM'
                    );
                EXCEPTION WHEN OTHERS THEN NULL;
                END;
            END LOOP;
        END LOOP;
        COMMIT;
    END IF;

    -- Ensure seat booking status entries exist
    SELECT COUNT(*) INTO V_SB_CNT FROM AIRLINE_FLIGHT_SEAT_BOOKING_TBL WHERE DYNAMIC_PRICE_ID = P_DYNAMIC_PRICE_ID;
    IF V_SB_CNT = 0 THEN
        INSERT INTO AIRLINE_FLIGHT_SEAT_BOOKING_TBL (SEAT_BOOKING_ID, DYNAMIC_PRICE_ID, SEAT_NO, STATUS, FINAL_SEAT_PRICE)
        SELECT AIRLINE_FLIGHT_SEAT_BOOKING_SEQ.NEXTVAL, P_DYNAMIC_PRICE_ID, SM.SEAT_NO, 'AVAILABLE', (V_BASE_PRICE + NVL(SM.PRICE_SURCHARGE, 0))
        FROM AIRLINE_FLIGHT_SEAT_MSTR_TBL SM
        WHERE SM.FLIGHT_ID = V_FLIGHT_ID;
        COMMIT;
    END IF;


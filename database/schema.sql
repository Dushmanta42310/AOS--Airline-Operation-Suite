CREATE OR REPLACE PROCEDURE AIRLINE_GET_USER_PROFILE_USP (
    P_USER_IDENTIFIER IN VARCHAR2,
    P_LOGIN_MODE      IN VARCHAR2,
    P_USER_ID         OUT NUMBER,
    P_USERNAME        OUT VARCHAR2,
    P_PASSPORT_IMG    OUT VARCHAR2,

)
IS
BEGIN
    IF P_LOGIN_MODE = 'U' THEN
        SELECT USER_ID, USERNAME, PASSPORT_IMG
        INTO P_USER_ID, P_USERNAME, P_PASSPORT_IMG
        FROM AIRLINE_USER_MSTR_TBL
        WHERE LOWER(USERNAME) = LOWER(P_USER_IDENTIFIER);
    ELSE
        SELECT USER_ID, USERNAME, PASSPORT_IMG
        INTO P_USER_ID, P_USERNAME, P_PASSPORT_IMG
        FROM AIRLINE_USER_MSTR_TBL
        WHERE MOBILENO = TO_NUMBER(P_USER_IDENTIFIER);
    END IF;

    BEGIN
        SELECT r.ROLE_NAME
        INTO P_ROLE_NAME
        FROM AIRLINE_USER_ROLE_MAP_TBL urm
        JOIN AIRLINE_ROLE_MSTR_TBL r ON urm.ROLE_ID = r.ROLE_ID
        WHERE urm.USER_ID = P_USER_ID
          AND urm.IS_ACTIVE = 'Y'
          AND r.IS_ACTIVE = 'Y';

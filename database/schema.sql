CREATE OR REPLACE PROCEDURE airline_flight_create_usp(
    p_flight_id    IN NUMBER,
    p_flight_no    IN VARCHAR2,
    p_company_id   IN NUMBER,
    p_flight_name  IN VARCHAR2,
    p_total_seats  IN NUMBER DEFAULT 180,
    p_data         OUT VARCHAR2
)
IS 
    v_count NUMBER;
    v_new_flight_id NUMBER;
    v_seats_total NUMBER := NVL(p_total_seats, 180);
    v_rows NUMBER;
    v_cols VARCHAR2(6) := 'ABCDEF';
    v_col_char CHAR(1);
    v_seat_no VARCHAR2(10);
    v_seat_class VARCHAR2(20);
    v_seat_type VARCHAR2(20);
    v_surcharge NUMBER(10,2);
BEGIN
    SELECT COUNT(*) INTO v_count FROM AIRLINE_FLIGHT_MSTR_TBL
    WHERE UPPER(FLIGHT_NO) = UPPER(P_FLIGHT_NO);

    IF v_count > 0 THEN 
        p_data := 'The Flight Already Exists';
    ELSE 
        v_new_flight_id := AIRLINE_FLIGHT_MSTR_TBL_SEQ.NEXTVAL;

        INSERT INTO AIRLINE_FLIGHT_MSTR_TBL (
            FLIGHT_ID, FLIGHT_NO, COMPANY_ID, FLIGHT_NAME, TOTAL_SEATS, CREATED_BY, CREATED_IP
        ) VALUES (
            v_new_flight_id, p_flight_no, p_company_id, p_flight_name, v_seats_total, 'Dushmabnta', '1001.1001.5'
        );

        -- Auto-populate 30 rows x 6 columns seat matrix layout for this flight model
        v_rows := CEIL(v_seats_total / 6);
        IF v_rows < 1 THEN v_rows := 30; END IF;

        FOR r IN 1..v_rows LOOP
            FOR c IN 1..6 LOOP
                v_col_char := SUBSTR(v_cols, c, 1);
                v_seat_no := r || v_col_char;

                -- Determine seat class & type
                IF r <= 3 THEN
                    v_seat_class := 'BUSINESS';
                    v_surcharge := 1500.00;
                ELSIF r <= 6 THEN
                    v_seat_class := 'PREMIUM';
                    v_surcharge := 500.00;
                ELSIF r IN (10, 11) THEN
                    v_seat_class := 'ECONOMY';
                    v_surcharge := 300.00; -- Exit row extra legroom
                ELSE
                    v_seat_class := 'ECONOMY';
                    v_surcharge := 0.00;
                END IF;

                IF v_col_char IN ('A', 'F') THEN
                    v_seat_type := 'WINDOW';
                    IF v_seat_class = 'ECONOMY' AND r NOT IN (10, 11) THEN
                        v_surcharge := 150.00;
                    END IF;
                ELSIF v_col_char IN ('C', 'D') THEN
                    v_seat_type := 'AISLE';
                    IF v_seat_class = 'ECONOMY' AND r NOT IN (10, 11) THEN
                        v_surcharge := 100.00;
                    END IF;
                ELSE
                    v_seat_type := 'MIDDLE';
                END IF;

                INSERT INTO AIRLINE_FLIGHT_SEAT_MSTR_TBL (
                    SEAT_ID, FLIGHT_ID, SEAT_NO, SEAT_ROW, SEAT_COL, SEAT_CLASS, SEAT_TYPE, PRICE_SURCHARGE, CREATED_BY
                ) VALUES (
                    AIRLINE_FLIGHT_SEAT_MSTR_SEQ.NEXTVAL, v_new_flight_id, v_seat_no, r, v_col_char, v_seat_class, v_seat_type, v_surcharge, 'SYSTEM'
                );
            END LOOP;
        END LOOP;

        p_data := 'Data Inserted Sucessfully';
        COMMIT;
    END IF;

EXCEPTION 
    WHEN OTHERS THEN
        ROLLBACK;
        p_data := SQLERRM;
END airline_flight_create_usp;

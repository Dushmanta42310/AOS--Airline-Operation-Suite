CREATE OR REPLACE PROCEDURE AIRLINE_CITY_CREATE_USP (
    P_CITYNAME    IN VARCHAR2,
    P_STATENAME   IN VARCHAR2,
    P_COUNTRYNAME IN VARCHAR2,
    P_ACTION      IN VARCHAR2,
    P_CURSOR      OUT SYS_REFCURSOR,
    P_DATA        OUT VARCHAR2
)
IS
    V_COUNT NUMBER;
BEGIN
    IF P_ACTION = 'INSERT' THEN
        SELECT COUNT(*)
        INTO V_COUNT

        SELECT PASSENGER_ID, PASSENGER_NAME, MOBILE_NO, EMAIL_ID, PASSPORT_NO
        FROM AIRLINE_PASSENGERS_REGD_FORM_MSTR_TBL
        WHERE IS_ACTIVE = 'Y' OR IS_ACTIVE IS NULL
        ORDER BY PASSENGER_NAME;


            P_CURRENT_PRICE,
            'Y',
            SYSTIMESTAMP,
            'DUSHMANTA',
            '100.125.49.24'
        );

        -- Initialize seat booking status entries for this dynamic flight schedule
        INSERT INTO AIRLINE_FLIGHT_SEAT_BOOKING_TBL (
            SEAT_BOOKING_ID, DYNAMIC_PRICE_ID, SEAT_NO, STATUS, FINAL_SEAT_PRICE
        )
        SELECT 
            AIRLINE_FLIGHT_SEAT_BOOKING_SEQ.NEXTVAL,
            V_NEW_DP_ID,
            SM.SEAT_NO,
            'AVAILABLE',
            (P_CURRENT_PRICE + NVL(SM.PRICE_SURCHARGE, 0))
        FROM AIRLINE_FLIGHT_SEAT_MSTR_TBL SM
        WHERE SM.FLIGHT_ID = P_FLIGHT_ID
          AND SM.IS_ACTIVE = 'Y';


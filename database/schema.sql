CREATE OR REPLACE PROCEDURE AIRLINE_AIRPORT_CREATE_USP (
    P_AIRPORTNAME IN VARCHAR2,
    P_AIRPORTCODE IN VARCHAR2,
    P_CITY_ID     IN VARCHAR2,
    P_ACTION      IN VARCHAR2,
    P_CURSOR      OUT SYS_REFCURSOR,
    P_DATA        OUT VARCHAR2
)
IS
    V_COUNT NUMBER;
BEGIN
    IF P_ACTION = 'DROPDOWN' THEN
        OPEN P_CURSOR FOR
            SELECT CITY_ID, CITY_NAME
            FROM AIRLINE_CITY_MSTR_TBL
            WHERE IS_ACTIVE = 'Y'
            ORDER BY CITY_NAME;

        P_DATA := 'CITY LIST FETCHED SUCCESSFULLY';

    ELSIF P_ACTION = 'SELECT' THEN
        OPEN P_CURSOR FOR
            SELECT A.AIRPORT_ID, A.AIRPORT_NAME, A.AIRPORT_CODE, A.CITY_ID, C.CITY_NAME, C.COUNTRY_NAME
            FROM AIRLINE_AIRPORT_MSTR_TBL A
            LEFT JOIN AIRLINE_CITY_MSTR_TBL C ON A.CITY_ID = C.CITY_ID
            WHERE A.IS_ACTIVE = 'Y' OR A.IS_ACTIVE IS NULL
            ORDER BY A.AIRPORT_NAME;

        P_DATA := 'AIRPORT LIST FETCHED SUCCESSFULLY';

    ELSIF P_ACTION = 'INSERT' THEN
        SELECT COUNT(*)
        INTO V_COUNT
        FROM AIRLINE_AIRPORT_MSTR_TBL
        WHERE UPPER(AIRPORT_NAME) = UPPER(P_AIRPORTNAME)
          AND UPPER(AIRPORT_CODE) = UPPER(P_AIRPORTCODE);

        IF V_COUNT > 0 THEN
            P_DATA := 'THE AIRPORT IS ALREADY THERE';
        ELSE
            INSERT INTO AIRLINE_AIRPORT_MSTR_TBL
                (AIRPORT_ID, AIRPORT_NAME, AIRPORT_CODE, CITY_ID, CREATED_BY, CREATED_IP)
            VALUES
                (AIRLINE_AIRPORT_MSTR_SEQ.NEXTVAL,
                 UPPER(P_AIRPORTNAME),
                 UPPER(P_AIRPORTCODE),
                 TO_NUMBER(P_CITY_ID),
                 'DUSHMANTA',
                 '100.125.49.24');

            P_DATA := 'AIRPORT INSERTED SUCCESSFULLY';
            COMMIT;
        END IF;

    ELSE
        P_DATA := 'INVALID ACTION';
    END IF;
END AIRLINE_AIRPORT_CREATE_USP;
/

CREATE OR REPLACE PROCEDURE AIRLINE_ASSIGN_OR_UPDATE_ROLE_TO_USER_USP (
    P_USER_ID      IN NUMBER,
    P_ROLE_ID      IN NUMBER,
    P_CREATED_BY   IN VARCHAR2,
    P_CREATED_IP   IN VARCHAR2,
    P_DATA         OUT VARCHAR2
)
IS
    V_ROLE_COUNT NUMBER;
    V_USER_COUNT NUMBER;
BEGIN
    SELECT COUNT(*)
    INTO V_ROLE_COUNT
    FROM AIRLINE_ROLE_MSTR_TBL
    WHERE ROLE_ID = P_ROLE_ID
      AND IS_ACTIVE = 'Y';

    IF V_ROLE_COUNT = 0 THEN
        P_DATA := 'ROLE IS NOT ACTIVE';
        RETURN;
    END IF;

    SELECT COUNT(*)
    INTO V_USER_COUNT
    FROM AIRLINE_USER_ROLE_MAP_TBL
    WHERE USER_ID = P_USER_ID;

    IF V_USER_COUNT > 0 THEN
        UPDATE AIRLINE_USER_ROLE_MAP_TBL
        SET ROLE_ID      = P_ROLE_ID,
            UPDATED_TIME = SYSTIMESTAMP,
            UPDATED_BY   = P_CREATED_BY,
            UPDATED_IP   = P_CREATED_IP
        WHERE USER_ID = P_USER_ID;
        P_DATA := 'ROLE UPDATED SUCCESSFULLY';
    ELSE
        INSERT INTO AIRLINE_USER_ROLE_MAP_TBL
            (USER_ID, ROLE_ID, IS_ACTIVE, CREATED_BY, CREATED_IP)
        VALUES
            (P_USER_ID, P_ROLE_ID, 'Y', P_CREATED_BY, P_CREATED_IP);
        P_DATA := 'ROLE ASSIGNED SUCCESSFULLY';
    END IF;
    COMMIT;

EXCEPTION
    WHEN OTHERS THEN
        ROLLBACK;
        P_DATA := SQLERRM;
END AIRLINE_ASSIGN_OR_UPDATE_ROLE_TO_USER_USP;
/

CREATE OR REPLACE PROCEDURE AIRLINE_ASSIGN_ROLE_SCREEN_USP (
    P_USERS OUT SYS_REFCURSOR,

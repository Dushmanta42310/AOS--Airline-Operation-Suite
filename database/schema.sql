CREATE OR REPLACE PROCEDURE AIRLINE_MENU_OPERATION_USP (
    P_MENU_ID      IN VARCHAR2,
    P_MENUNAME     IN VARCHAR2,
    P_ACTION       IN VARCHAR2,
    P_DATA_CREATE  OUT VARCHAR2,
    P_DATA_DELETE  OUT VARCHAR2,
    P_CURSOR       OUT SYS_REFCURSOR
)
IS
    V_COUNT1 NUMBER := 0;
    V_COUNT2 NUMBER := 0;
BEGIN
    IF UPPER(P_ACTION) = 'CREATE' THEN
        SELECT COUNT(*) INTO V_COUNT1 FROM AIRLINE_MENU_MSTR_TBL
        WHERE UPPER(MENU_NAME) = UPPER(TRIM(P_MENUNAME));
        IF V_COUNT1 > 0 THEN
            P_DATA_CREATE := 'THE MENU ALREADY EXISTS';
        ELSE
            INSERT INTO AIRLINE_MENU_MSTR_TBL (MENU_ID, MENU_NAME)
            VALUES (AIRLINE_MENU_MSTR_SEQ.NEXTVAL, P_MENUNAME);
            P_DATA_CREATE := 'MENU CREATED SUCCESSFULLY';
        END IF;

    ELSIF UPPER(P_ACTION) = 'DROPDOWN' THEN
        OPEN P_CURSOR FOR
            SELECT MENU_ID, MENU_NAME
            FROM AIRLINE_MENU_MSTR_TBL
            ORDER BY MENU_NAME;

    ELSIF UPPER(P_ACTION) = 'DELETE' THEN
        SELECT COUNT(*) INTO V_COUNT2 FROM AIRLINE_MENU_MSTR_TBL
        WHERE MENU_ID = P_MENU_ID;
        IF V_COUNT2 = 0 THEN
            P_DATA_DELETE := 'THE MENU DOES NOT EXIST';
        ELSE
            DELETE FROM AIRLINE_MENU_MSTR_TBL
            WHERE MENU_ID = P_MENU_ID;
            P_DATA_DELETE := 'MENU DELETED SUCCESSFULLY';
        END IF;
    END IF;
